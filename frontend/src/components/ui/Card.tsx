export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = true, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-3xl border border-card-border bg-card-bg dark:bg-card-bg/60 dark:backdrop-blur-md text-foreground shadow-sm shadow-shadow-color",
      hoverable && "hover:shadow-md hover:shadow-shadow-color/10 hover:-translate-y-0.5 transition-all duration-300",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

